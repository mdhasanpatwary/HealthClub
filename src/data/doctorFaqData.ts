/**
 * Generates high-converting BLUF (Bottom Line Up Front) answer capsule text
 * for Google Assistant, Siri, ChatGPT Search, PerplexityBot and Gemini AI Overviews.
 * Target: 40-60 concise, factual, direct words with explicit entity linkages.
 */
export function generateDoctorQuickSummary(doctor: Doctor): string {
  const cleanName = doctor.name.trim();
  const cleanSpecialty = doctor.specialty.trim();
  const roomText = doctor.roomNo ? ` (রুম নং: ${doctor.roomNo.trim()})` : "";
  const feeText = doctor.consultationFee ? `। ভিজিট ফি: ${doctor.consultationFee.trim()}` : "";

  return `${cleanName} (${doctor.degrees || cleanSpecialty}) ফেনী সদরের একজন বিশেষজ্ঞ ${cleanSpecialty}। তাঁর নিয়মিত চেম্বার ${doctor.chamberName}, ${doctor.chamberAddress}${roomText}। রোগী দেখার সময়সূচী: ${doctor.visitingDays} (${doctor.visitingHours})${feeText}। অ্যাপয়েন্টমেন্ট ও সিরিয়াল হটলাইন: ${doctor.serialPhone}। প্রেসক্রিপশনকৃত ডায়াগনস্টিক টেস্টে হেলথ ক্লাব মেম্বারদের জন্য ফেনী সদরের পার্টনার সেন্টারে রয়েছে ১০-৩০% মেম্বার ছাড়।`;
}

